def say(msg=""):
    print(msg, flush=True)


def banner(text, color=CYAN):
    say()
    say(f"{color}{'=' * 78}{OFF}")
    say(f"{color}{BOLD}{text}{OFF}")
    say(f"{color}{'=' * 78}{OFF}")


def read_key():
    """One keypress, no Enter. cbreak is entered and left around each read so
    subprocesses (transcribe's push-to-talk, ingest's cv2 window) get a normal
    terminal."""
    if not sys.stdin.isatty():
        ch = sys.stdin.read(1)
        return ch if ch else "q"
    fd = sys.stdin.fileno()
    old = termios.tcgetattr(fd)
    try:
        tty.setcbreak(fd)
        return sys.stdin.read(1)
    finally:
        termios.tcsetattr(fd, termios.TCSADRAIN, old)


def gate(st, prompt, is_motion=False):
    """Block until the operator advances. Returns 'go' or 'again'.

    Arm motions are NOT gated (operator's decision, 2026-08-30): the demo is the
    robot trying something and reacting, not a human driving it key by key. They
    run as soon as the beat reaches them, on the SPACE the operator already
    pressed for the step before. Beat pacing is unchanged — every non-motion
    step still waits — and Ctrl-C is still the e-stop, freezing and holding.
    """
    if st.rehearse:
        say(f"{DIM}[rehearse] auto-advance: {prompt}{OFF}")
        return "go"
    if is_motion:
        say(f"\n{YEL}[ARM]{OFF} {BOLD}{prompt}{OFF}")
        say(f"{DIM}  running now — Ctrl-C freezes and holds{OFF}")
        return "go"
    mark = ""
    while True:
        say()
        say(f"{mark}{BOLD}{prompt}{OFF}")
        say(f"{DIM}  SPACE/n=go  r=redo  t=input mode ({'TYPED' if st.text_mode else 'SPOKEN'})"
            f"  h=recover-home  q=quit{OFF}")
        k = read_key()
        if k in (" ", "n", "\r", "\n"):
            return "go"
        if k == "r":
            return "again"
        if k == "t":
            st.text_mode = not st.text_mode
            say(f"{GRN}  input mode -> {'TYPED' if st.text_mode else 'SPOKEN'}{OFF}")
            continue
        if k == "h":
            recover_home()
            continue
        if k == "c":
            converse(st)
            continue
        if k == "q":
            raise Quit()


def recover_home():
    from arm import arm_io, safety

    if not safety.is_frozen():
        say(f"{DIM}  arm is not frozen; nothing to recover{OFF}")
        return
    say("  arm is frozen. arm_io.recover_home() will ask you to confirm before it moves.")
    try:
        arm_io.recover_home()
    except Exception as exc:  # noqa: BLE001 - stage code, surface and continue
        say(f"{RED}  recover_home failed: {exc}{OFF}")


