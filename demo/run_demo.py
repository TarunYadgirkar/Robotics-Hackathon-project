def _instruction_slots(instruction):
    """Computed facts about what the human said. Measured, never asserted:
    nothing here claims the attempt worked, only that words were received."""
    # Slot names are Agent D's, taken from voice/speak.py's attempt_result
    # template — D authors the wording, run_demo only supplies measured values.
    words = [w for w in instruction.split() if w.strip()]
    return {
        "n_instruction_words": len(words),
        "instruction_chars": len(instruction),
        "n_matching_demos": 0,
    }


def _augment_decision(path, extra_slots, label):
    """Write a copy of the decision JSON with extra COMPUTED slots merged into
    utterance_slots, so voice/speak.py can interpolate them without brain/ having
    to know about the teaching loop. evidence gets the same numbers for the panel."""
    decision = json.loads(Path(path).read_text())
    decision["utterance_slots"] = {**decision.get("utterance_slots", {}), **extra_slots}
    decision["evidence"] = {**decision.get("evidence", {}), **extra_slots}
    out = DECISION_DIR / f"{label}.json"
    out.write_text(json.dumps(decision, indent=2))
    return out


