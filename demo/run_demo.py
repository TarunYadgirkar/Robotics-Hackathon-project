SCRIPTED_STEPS = [
    ("wake", "greeting", "greeting", None),
    ("decline", "refusal", "abstain_howto", GOLDEN_QUERY),
    ("attempt", "close", "attempt_result", GOLDEN_QUERY),
    ("approach_can", "can_question", "can_grip_question", CAN_QUERY),
    ("can_grip_top", "can_close", "attempt_result", None),
]


def _scripted_decision_path(kind):
    return SCRIPTED_DIR / f"{kind}.json"


def build_scripted_cache(st):
    """Pre-synthesize the golden path so the backup needs no network on stage.

    The NUMBERS in the cached audio are still real: the decision JSONs are
    generated here by the real brain/decide.py, not written by hand.
    """
    import importlib.util
    spec = importlib.util.spec_from_file_location("sp", REPO_ROOT / "voice" / "speak.py")
    sp = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(sp)

    SCRIPTED_DIR.mkdir(parents=True, exist_ok=True)
    AUDIO_CACHE.mkdir(parents=True, exist_ok=True)

    base = subprocess.run([PY, str(REPO_ROOT / "brain" / "decide.py"), GOLDEN_QUERY],
                          cwd=REPO_ROOT, capture_output=True, text=True)
    decision = json.loads(base.stdout)
    _scripted_decision_path("greeting").write_text(json.dumps(decision, indent=2))
    _scripted_decision_path("refusal").write_text(json.dumps(decision, indent=2))

    taught = json.loads(json.dumps(decision))
    slots = _instruction_slots(INSTRUCTION_FALLBACK)
    taught["utterance_slots"] = {**taught["utterance_slots"], **slots}
    taught["evidence"] = {**taught["evidence"], **slots}
    _scripted_decision_path("close").write_text(json.dumps(taught, indent=2))

    can_raw = subprocess.run([PY, str(REPO_ROOT / "brain" / "decide.py"), CAN_QUERY],
                             cwd=REPO_ROOT, capture_output=True, text=True)
    can = json.loads(can_raw.stdout)
    _scripted_decision_path("can_question").write_text(json.dumps(can, indent=2))
    can_closed = json.loads(json.dumps(can))
    can_slots = _instruction_slots("hold it at the top")
    can_closed["utterance_slots"] = {**can_closed["utterance_slots"], **can_slots}
    can_closed["evidence"] = {**can_closed["evidence"], **can_slots}
    _scripted_decision_path("can_close").write_text(json.dumps(can_closed, indent=2))

    for _, kind, template, _q in SCRIPTED_STEPS:
        d = json.loads(_scripted_decision_path(kind).read_text())
        text, _ = sp.render(d, template_name=template)
        (AUDIO_CACHE / f"{kind}.txt").write_text(text + "\n")
        mp3 = AUDIO_CACHE / f"{kind}.mp3"
        try:
            dt = sp.synthesize_to_file(text, mp3)
            say(f"{GRN}  cached {mp3.name} ({mp3.stat().st_size} bytes, {dt:.2f}s){OFF}")
        except Exception as exc:  # noqa: BLE001
            say(f"{RED}  could not pre-synthesize {kind}: {exc}{OFF}")
            say(f"{YEL}  scripted mode will fall back to macOS 'say' for this line{OFF}")
    return True


def scripted_backup(st):
    """Fully deterministic backup: no mic, no LLM, no network, no ElevenLabs call.
    Sanctioned by the judge AS A BACKUP — so it is labelled as one on screen."""
    banner("[SCRIPTED BACKUP] — deterministic, no mic / no LLM / no network", YEL)
    say(f"{YEL}  This is the sanctioned backup path. Say so out loud: the numbers in it "
        f"are real (generated by brain/decide.py), the timing is not live.{OFF}")

    for gesture_name, kind, _template, operator_line in SCRIPTED_STEPS:
        cue = {
            "refusal": f'OPERATOR SAYS: "{GOLDEN_QUERY}"',
            "close": "OPERATOR describes how to fold paper (freely, ~6s)",
            "can_question": f'OPERATOR holds up the can and SAYS: "{CAN_QUERY}"',
            "can_close": 'OPERATOR SAYS: "hold it at the top"',
        }.get(kind)
        if cue:
            say()
            say(f"{BOLD}  {cue}{OFF}")
        if gate(st, f"[SCRIPTED BACKUP] {kind}: gesture '{gesture_name}' then cached audio") != "go":
            continue

        gdir = (REPO_ROOT / "arm" / "gestures") if st.sim_arm else None
        if gdir is None:
            from arm import arm_io
            gdir = Path(arm_io.GESTURE_DIR)
        traj = gdir / f"{gesture_name}.json"
        if not traj.exists():
            fb = {"wake": "attention", "approach_can": "attention",
                  "can_grip_top": "attempt", "can_grip_bottom": "attempt"}.get(
                      gesture_name, "task_demo")
            say(f"{YEL}  {gesture_name}.json missing — using {fb}{OFF}")
            traj = gdir / f"{fb}.json"
        arm_motion(st, "replay", gesture_name, 10.0, path=traj)

        mp3 = AUDIO_CACHE / f"{kind}.mp3"
        txt = (AUDIO_CACHE / f"{kind}.txt")
        line = txt.read_text().strip() if txt.exists() else ""
        say(f"{BOLD}  SPOKEN [cached]: {line}{OFF}")
        st.log(f"scripted {kind} spoken [cached]: {line!r}")
        if st.no_audio:
            continue
        if mp3.exists():
            subprocess.run(["afplay", str(mp3)])
        else:
            say(f"{YEL}  no cached mp3 — falling back to macOS say{OFF}")
            subprocess.run(["say", "-v", "Samantha", line])

    banner("[SCRIPTED BACKUP] COMPLETE", YEL)


# ---------------------------------------------------------------- converse mode

NOT_UNDERSTOOD_PATH = DECISION_DIR / "_not_understood.json"


def _not_understood_decision():
    """A decision-shaped stub so speak.py can render the no-slot fixed line
    through the identical template mechanism as everything else."""
    NOT_UNDERSTOOD_PATH.parent.mkdir(parents=True, exist_ok=True)
    NOT_UNDERSTOOD_PATH.write_text(json.dumps({
        "query": "", "tier": "abstain", "matched_task_id": None, "match_score": 0.0,
        "coverage_detail": {"covered": [], "uncovered": []},
        "evidence": {"n_matching_demos": 0}, "utterance_slots": {},
    }, indent=2))
    return NOT_UNDERSTOOD_PATH


def respond_to(st, transcript, label):
    """One conversational turn: decide, then ALWAYS speak and gesture per tier."""
    # Routed before the zero-coverage noise guard on purpose: "put this can upside
    # down" legitimately scores 0.0 (every content word is unknown), which is the
    # honest result but would otherwise be swallowed as noise.
    if mentions_can(transcript):
        if _tokens(transcript) & PICKUP_WORDS:
            return flip_beat(st, transcript, label)
        return can_beat(st, transcript, label)

    got = decide(st, transcript, label)
    if got is None:
        speak(st, _not_understood_decision(), label, template="not_understood")
        return
    path, dec = got
    tier = dec["tier"]

    # Computed, not a guess: coverage 0.0 means not one content word in the
    # utterance matched anything in 50 task names — that is noise, not a task I
    # don't know. "bottle flip" scores 0.5 and still gets the full teaching loop.
    if tier == "abstain" and not dec.get("match_score"):
        say(f"{DIM}  match_score 0.0 — no content word matched anything; treating as "
            f"noise rather than a task{OFF}")
        speak(st, _not_understood_decision(), label, template="not_understood")
        return

    if tier == "act":
        # Converse breaks the act-silent rule on purpose: in free conversation
        # silence is indistinguishable from a crash. BEAT 1 stays silent.
        speak(st, path, label, template="act_confirm", allow_llm=True)
        arm_motion(st, "replay", "task_demo", 19.4)
    elif tier == "ask":
        arm_motion(st, "gesture", "attention", 3.4)
        speak(st, path, label, allow_llm=True)
        panel(st, path, label)
        _resolve_ask(st, path, label)
    else:
        arm_motion(st, "gesture", "decline", 7.4)
        speak(st, path, label, template="abstain_howto", allow_llm=True)
        panel(st, path, label)
        teach_and_attempt(st, path, label)


def converse(st):
    """Free conversation. Listen, decide, always respond out loud, repeat.

    Every response is still a fixed template filled with numbers computed by
    brain/decide.py at runtime — no LLM. That holds in open conversation because
    decide.py already handles arbitrary queries: coverage is computed against the
    real task names whatever you say to it.
    """
    banner("CONVERSE — say anything; it answers with what it measured", GRN)
    say(f"{DIM}  q ends conversation and returns. Empty capture twice -> typed input.{OFF}")
    empty_streak = 0
    turn = 0

    scripted = list(st.converse_script) if st.rehearse else None
    while True:
        turn += 1
        if scripted is not None:
            if not scripted:
                say(f"{DIM}  [rehearse] converse script exhausted{OFF}")
                return
            st.scripted[f"converse{turn}"] = scripted.pop(0)
        elif not st.text_mode:
            say()
            say(f"{BOLD}SPACE to speak (6s), t=typed, q=end conversation{OFF}")
            k = read_key()
            if k == "q":
                say(f"{GRN}  ending conversation{OFF}")
                return
            if k == "t":
                st.text_mode = not st.text_mode
                say(f"{GRN}  input mode -> {'TYPED' if st.text_mode else 'SPOKEN'}{OFF}")
                continue

        transcript = capture_query(st, "", f"converse{turn}", seconds=6)
        if not transcript:
            empty_streak += 1
            speak(st, _not_understood_decision(), f"converse{turn}",
                  template="not_understood")
            if empty_streak >= 2 and not st.text_mode:
                say(f"{YEL}  two empty captures — switching to typed input{OFF}")
                st.text_mode = True
            continue
        empty_streak = 0
        if transcript.strip().lower() in ("quit", "stop the demo", "end conversation"):
            say(f"{GRN}  ending conversation{OFF}")
            return
        respond_to(st, transcript, f"converse{turn}")


# ------------------------------------------------------------------------- main

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--text-mode", action="store_true", help="start in typed-input mode")
    ap.add_argument("--no-audio", action="store_true", help="print the spoken text, do not play it")
    ap.add_argument("--beat", type=int, default=1, help="start at this beat (1-4)")
    ap.add_argument("--rehearse", action="store_true",
                    help="drive all 4 beats through --text non-interactively")
    ap.add_argument("--beats", action="store_true",
                    help="run the original scripted 4-beat sequence instead of the golden path")
    ap.add_argument("--scripted", action="store_true",
                    help="deterministic backup: cached audio, no mic/LLM/network")
    ap.add_argument("--build-cache", action="store_true",
                    help="pre-synthesize the scripted backup's audio, then exit")
    ap.add_argument("--no-llm", action="store_true",
                    help="force fixed templates; never call voice/llm_phrase.py")
    ap.add_argument("--converse", action="store_true",
                    help="go straight into free conversation instead of the scripted beats")
    ap.add_argument("--flip", action="store_true",
                    help="go straight into the flip beat: real can pickup -> told 'flip' -> "
                         "honest abstain -> 'hold it at the top' -> release on the way up")
    ap.add_argument("--sim-arm", action="store_true",
                    help="print what the arm would do instead of commanding it "
                         "(auto-enabled by --rehearse when the backend is real hardware)")
    args = ap.parse_args()

    # A rehearsal must never command a live arm as a side effect. Agent C added an
    # ARM_FORCE_SIM hook to arm/facts.py, so a rehearsal forces the simulator while
    # still running the REAL arm_io / motion / safety code — strictly better than
    # stubbing the arm out, which is what --sim-arm still does as an escape hatch.
    if args.rehearse and not args.sim_arm:
        os.environ["ARM_FORCE_SIM"] = "1"

    st = State(args)
    DECISION_DIR.mkdir(parents=True, exist_ok=True)
    PANEL_DIR.mkdir(parents=True, exist_ok=True)

    banner("I DON'T KNOW HOW TO DO THAT YET")
    if st.sim_arm:
        say(f"  arm backend : {YEL}STUBBED (--sim-arm){OFF} — no motion will be commanded")
    else:
        from arm import arm_io
        d = arm_io.describe()
        say(f"  arm backend : {d['backend']}  (simulated={d['simulated']}, "
            f"FACTS HARDWARE_PRESENT={d['hardware_present_facts']})")
        if not d["simulated"]:
            say(f"{RED}{BOLD}  REAL ARM. Motions are NOT individually gated: they run when "
                f"the beat decides, including in response to a spoken reply.{OFF}")
            say(f"{RED}  Ctrl-C freezes and holds. Keep the workspace clear.{OFF}")
    say(f"  input mode  : {'TYPED' if st.text_mode else 'SPOKEN (listen/transcribe.py)'}")
    say(f"  sim render  : ARM_SIM_RENDER={os.environ.get('ARM_SIM_RENDER')} "
        f"(0 = no per-motion GIF, stills already in arm/sim_out/)")
    say()
    say(f"{BOLD}  SAY THIS OUT LOUD, ONCE, EARLY:{OFF}")
    say(f"{BOLD}  \"{DISCLOSURE}\"{OFF}")

    rc = 0
    try:
        if args.build_cache:
            build_scripted_cache(st)
            return 0

        step(st, "home the arm before anything else (~1s)", lambda: _home(st), is_motion=True)

        if args.scripted:
            scripted_backup(st)
        elif args.flip:
            flip_beat(st, "pick up the can")
        elif args.converse:
            converse(st)
        elif args.beats:
            for i, beat in enumerate(BEATS, start=1):
                if i < args.beat:
                    continue
                beat(st)
        else:
            golden_path(st)

        if st.rehearse and not args.scripted:
            # One rehearsal pass covers everything: the beats and the scripted
            # backup, on top of whichever mode ran above.
            for i, beat in enumerate(BEATS, start=1):
                beat(st)
            st.converse_script = ["garment iron press", CAN_QUERY, "wubbalubba dubdub"]
            converse(st)
            scripted_backup(st)
        banner("DEMO COMPLETE", GRN)
    except Quit:
        say(f"\n{YEL}quit — arm left where it is, not homed behind your back{OFF}")
    except KeyboardInterrupt:
        say(f"\n{RED}interrupted{OFF}")
        rc = 130
    finally:
        close_panel(st)
        if st.rehearse:
            out = REPO_ROOT / "demo" / "rehearsal_transcript.txt"
            out.write_text("\n".join(st.transcript) + "\n")
            say(f"\n{DIM}rehearsal transcript -> {out}{OFF}")
    return rc


def _home(st):
    if st.sim_arm:
        say(f"{DIM}  [sim-arm] would home — hardware not commanded{OFF}")
        return
    t0 = time.time()
    try:
        from arm import arm_io
        arm_io.home()
    except BaseException as exc:  # noqa: BLE001 — see arm_motion
        say(f"{RED}{BOLD}  [ARM OFFLINE — continuing without motion]{OFF}")
        say(f"{DIM}  {type(exc).__name__}: {exc}{OFF}")
        st.log(f"arm home: OFFLINE ({type(exc).__name__})")
        return
    say(f"{GRN}  arm: home complete ({time.time() - t0:.1f}s){OFF}")
    st.log(f"arm home: complete in {time.time() - t0:.1f}s")


if __name__ == "__main__":
    sys.exit(main())
